WHERE OPE_ALPHA17 = 'VALEUR_ERREUR_ICI'
   OR OPE_ALPHA17 LIKE '%VALEUR_ERREUR_ICI%'
   OR OPE_REDO = 'VALEUR_ERREUR_ICI'
   OR OPE_REDO LIKE '%VALEUR_ERREUR_ICI%';

