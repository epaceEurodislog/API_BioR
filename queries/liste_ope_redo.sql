-- 17. ÉCHANTILLON COMPLET : Voir les différents cas de figure
SELECT TOP 20
    OPE_KEYU,
    CASE 
        WHEN OPE_ALPHA17 IS NULL THEN '🔴 NULL'
        WHEN OPE_ALPHA17 = '' THEN '🟡 VIDE'
        WHEN LTRIM(RTRIM(OPE_ALPHA17)) = '' THEN '🟡 ESPACES'
        ELSE '🟢 RENSEIGNÉ'
    END as STATUT_ALPHA17,
    '[' + ISNULL(OPE_ALPHA17, 'NULL') + ']' as ALPHA17_AVEC_CROCHETS,
    OPE_REDO,
    OPE_STAT
FROM OPE_DAT
ORDER BY OPE_KEYU DESC;

-- 18. RECHERCHE PATTERN SPÉCIFIQUE : Formats d'OPE_ALPHA17
SELECT DISTINCT
    CASE 
        WHEN OPE_ALPHA17 IS NULL THEN 'NULL'
        WHEN OPE_ALPHA17 = '' THEN 'VIDE'
        WHEN OPE_ALPHA17 LIKE '%-%' THEN 'CONTIENT_TIRET'
        WHEN OPE_ALPHA17 LIKE '%.%' THEN 'CONTIENT_POINT'
        WHEN ISNUMERIC(OPE_ALPHA17) = 1 THEN 'NUMERIQUE_SEUL'
        WHEN LEN(OPE_ALPHA17) > 20 THEN 'TROP_LONG'
        ELSE 'AUTRE_FORMAT'
    END as TYPE_FORMAT,
    COUNT(*) as NOMBRE_OCCURRENCES,
    MIN(OPE_ALPHA17) as EXEMPLE_VALEUR
FROM OPE_DAT
GROUP BY 
    CASE 
        WHEN OPE_ALPHA17 IS NULL THEN 'NULL'
        WHEN OPE_ALPHA17 = '' THEN 'VIDE'
        WHEN OPE_ALPHA17 LIKE '%-%' THEN 'CONTIENT_TIRET'
        WHEN OPE_ALPHA17 LIKE '%.%' THEN 'CONTIENT_POINT'
        WHEN ISNUMERIC(OPE_ALPHA17) = 1 THEN 'NUMERIQUE_SEUL'
        WHEN LEN(OPE_ALPHA17) > 20 THEN 'TROP_LONG'
        ELSE 'AUTRE_FORMAT'
    END
ORDER BY NOMBRE_OCCURRENCES DESC;

