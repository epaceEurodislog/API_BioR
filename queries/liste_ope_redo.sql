-- Requête SQL pour lister les OPE_REDO pour les tests de comptes rendus de préparation
-- Fichier : queries/liste_ope_redo.sql

-- 1. REQUÊTE PRINCIPALE : Liste des OPE_REDO avec informations essentielles
SELECT 
    OPE_KEYU,                                    -- Clé unique (int)
    ISNULL(OPE_REDO, '') as OPE_REDO,           -- Numéro de référence (varchar 50)
    ISNULL(OPE_ALPHA17, '') as OPE_ALPHA17,     -- Information complémentaire (varchar 255)
    ISNULL(OPE_CTRA, '') as OPE_CTRA,           -- Code transporteur (varchar 35)
    ISNULL(OPE_ALPHA40, '') as OPE_ALPHA40,     -- Champ alpha 40 (varchar 50)
    ISNULL(OPE_ALPHA41, '') as OPE_ALPHA41,     -- Champ alpha 41 (varchar 50)
    OPE_MODA,                                    -- Date de modification (date)
    ISNULL(OPE_TOP22, 0) as OPE_TOP22,          -- Champ numérique 22 (numeric)
    ISNULL(OPE_STAT, '') as OPE_STAT            -- Statut (varchar 10)
FROM OPE_DAT
WHERE OPE_KEYU IS NOT NULL
  AND OPE_REDO IS NOT NULL
  AND OPE_REDO != ''
ORDER BY OPE_KEYU DESC;

-- 2. REQUÊTE POUR TESTS SPÉCIFIQUES : Récents OPE_REDO seulement
SELECT TOP 20
    OPE_KEYU,
    OPE_REDO,
    OPE_STAT,
    OPE_MODA,
    OPE_CTRA
FROM OPE_DAT
WHERE OPE_REDO IS NOT NULL
  AND OPE_REDO != ''
  AND OPE_KEYU IS NOT NULL
ORDER BY OPE_KEYU DESC;

-- 3. REQUÊTE AVEC STATISTIQUES : Compter les lignes associées
SELECT 
    OPE.OPE_KEYU,
    OPE.OPE_REDO,
    OPE.OPE_STAT,
    OPE.OPE_MODA,
    COUNT(MIL.ART_CODE) as NB_LIGNES_ARTICLES
FROM OPE_DAT OPE
LEFT JOIN MIL_DAT MIL ON OPE.OPE_NoOE = MIL.OPE_NoOE
WHERE OPE.OPE_REDO IS NOT NULL
  AND OPE.OPE_REDO != ''
  AND OPE.OPE_KEYU IS NOT NULL
GROUP BY OPE.OPE_KEYU, OPE.OPE_REDO, OPE.OPE_STAT, OPE.OPE_MODA
ORDER BY OPE.OPE_KEYU DESC;

-- 4. REQUÊTE POUR VALIDATION : Vérifier les OPE_REDO uniques
SELECT 
    OPE_REDO,
    COUNT(*) as NOMBRE_OCCURRENCES
FROM OPE_DAT
WHERE OPE_REDO IS NOT NULL
  AND OPE_REDO != ''
GROUP BY OPE_REDO
HAVING COUNT(*) > 1
ORDER BY NOMBRE_OCCURRENCES DESC;

-- 5. RECHERCHE OPE_REDO SPÉCIFIQUE : Recherche par partie du numéro
-- Remplacer 'PARTIE_NUMERO' par une partie du OPE_REDO recherché
SELECT 
    OPE_KEYU,
    OPE_REDO,
    OPE_STAT,
    OPE_MODA,
    OPE_CTRA,
    OPE_ALPHA17
FROM OPE_DAT
WHERE OPE_REDO LIKE '%PARTIE_NUMERO%'
  AND OPE_REDO IS NOT NULL
ORDER BY OPE_KEYU DESC;

-- 6. RECHERCHE OPE_REDO EXACT : Pour un numéro précis
-- Remplacer 'NUMERO_EXACT' par le OPE_REDO exact recherché
