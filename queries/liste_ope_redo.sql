-- 24. VALIDATION GÉNÉRIQUE : Template pour vérifier n'importe quelle valeur d'erreur
-- Remplacer 'VALEUR_ERREUR_ICI' par la valeur du message d'erreur
SELECT 
    '🔍 TEMPLATE RECHERCHE ERREUR' as TYPE,
    OPE_KEYU,
    'TROUVÉ DANS: ' + 
    CASE 
        WHEN OPE_ALPHA17 = 'VALEUR_ERREUR_ICI' THEN 'OPE_ALPHA17 (EXACT)'
        WHEN OPE_ALPHA17 LIKE '%VALEUR_ERREUR_ICI%' THEN 'OPE_ALPHA17 (PARTIEL)'
