    SUM(CASE WHEN OPE_ALPHA17 IS NULL THEN 1 ELSE 0 END) as NULL_COUNT,
    SUM(CASE WHEN OPE_ALPHA17 = '' THEN 1 ELSE 0 END) as VIDE_COUNT,
    SUM(CASE WHEN OPE_ALPHA17 IS NOT NULL AND OPE_ALPHA17 != '' THEN 1 ELSE 0 END) as RENSEIGNE_COUNT
