-- 7. RECHERCHE AVEC PATTERN : Pour rechercher selon un motif
-- Exemples d'utilisation :
-- OPE_REDO LIKE 'BL%'        --> Commence par "BL"
-- OPE_REDO LIKE '%2024%'     --> Contient "2024"
-- OPE_REDO LIKE 'BL_____'    --> "BL" suivi de 5 caractères exactement
SELECT 
    OPE_KEYU,
    OPE_REDO,
    OPE_STAT,
    OPE_MODA
FROM OPE_DAT
WHERE OPE_REDO LIKE 'VOTRE_PATTERN'
  AND OPE_REDO IS NOT NULL
ORDER BY OPE_REDO;

-- 8. REQUÊTE DIAGNOSTIC COMPLÈTE : Structure des données pour un OPE_REDO spécifique
-- Remplacer 'VOTRE_OPE_REDO' par une valeur réelle pour tester
SELECT 
    'En-tête BL' as TYPE_DONNEE,
    OPE_KEYU as REFERENCE,
    OPE_REDO as NUMERO,
    OPE_STAT as STATUT,
    NULL as ART_CODE,
    NULL as QUANTITE
FROM OPE_DAT
WHERE OPE_REDO = 'VOTRE_OPE_REDO'

UNION ALL

SELECT 
    'Ligne article' as TYPE_DONNEE,
    CAST(OPE.OPE_KEYU AS VARCHAR(10)) as REFERENCE,
    OPE.OPE_REDO as NUMERO,
    NULL as STATUT,
    MIL.ART_CODE,
    CAST(MIL.MIL_QTTP AS VARCHAR(20)) as QUANTITE
FROM OPE_DAT OPE
INNER JOIN MIL_DAT MIL ON OPE.OPE_NoOE = MIL.OPE_NoOE
WHERE OPE.OPE_REDO = 'VOTRE_OPE_REDO'
ORDER BY TYPE_DONNEE, REFERENCE;

